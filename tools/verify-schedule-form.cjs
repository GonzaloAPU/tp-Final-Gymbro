/**
 * Prueba la lógica del formulario de asignación mediante simulaciones de servicios y estado. No sustituye la validación de horarios del servidor.
 * Guía de estudio general: docs/GUIA-DE-ESTUDIO.md.
 */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const { of } = require('rxjs');
const signal = initial => { let value = initial; const read = () => value; read.set = next => value = next; read.update = fn => value = fn(value); return read; };
const saved = [];
const routineService = { assignSchedule: (_routine, _day, schedule) => { saved.push(schedule.map(slot => ({...slot}))); return of({schedule}); } };
routineService.setFavorite = (_routine, _day, favorite) => of({favorite});
const auth = { user: () => ({ id: 'test-user' }) };
const compiled = ts.transpileModule(fs.readFileSync('frontend/src/app/components/dashboard.component.ts','utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, experimentalDecorators: true } }).outputText;
const output = {};
vm.runInNewContext(compiled, { exports: output, localStorage: { getItem: () => null }, require: name => {
  if (name === '@angular/core') return { ChangeDetectionStrategy:{Eager:1,OnPush:0}, Component: () => target => target, Input:()=>()=>{}, signal, inject: token => token === 'routines' ? routineService : auth };
  if (name === '@angular/common' || name === '@angular/router') return {};
  if (name.includes('routine.service')) return { RoutineService: 'routines' };
  if (name.includes('auth.service')) return { AuthService: 'auth' };
  if (name.includes('progress.service')) return { ProgressService: 'progress' };
  if (name.includes('profile-photo')) return { prepareProfilePhoto: async () => '' };
  return require(name);
} });
const dashboard = new output.DashboardComponent();
const endInput = {value: ''};
dashboard.suggestScheduleEnd('19:00', endInput);
assert.equal(endInput.value, '19:30');
dashboard.suggestScheduleEnd('23:45', endInput);
assert.equal(endInput.value, '', 'No propone un final anterior al inicio al cruzar medianoche');
const day = { id: 'day', schedule: [] };
dashboard.routines.set([{id:'routine', days:[day]}]);
dashboard.openSchedule(day);
dashboard.saveSchedule('routine','day','3','18:00','19:00');
assert.equal(saved.length,1);
assert.equal(saved[0][0].weekday,3);
assert.equal(saved[0][0].start,'18:00');
assert.equal(dashboard.routines()[0].days[0].schedule.length,1);
dashboard.openSchedule(dashboard.routines()[0].days[0]);
dashboard.saveSchedule('routine','day','1','08:00','09:00');
assert.equal(saved[1].length,1,'Unchanged form must not add a default range');
dashboard.openSchedule({id:'day',schedule:[]});
dashboard.addSlot('1','08:00','09:00');
dashboard.saveSchedule('routine','day','1','08:00','09:00');
assert.equal(saved[2].length,1,'Add followed by Save must not duplicate the range');
dashboard.openSchedule(dashboard.routines()[0].days[0]);
dashboard.removeSlot(0);
dashboard.saveSchedule('routine','day','1','08:00','09:00');
assert.equal(saved[3].length,0,'Explicitly clearing the schedule must remain possible');
dashboard.openSchedule({id:'day',schedule:[]});
dashboard.saveSchedule('routine','day','1','10:00','09:00');
assert.equal(saved.length,4,'Invalid range must not be saved');
assert.ok(dashboard.scheduleError());
auth.user = () => ({ id: 'test-user', restDays: [2] });
dashboard.openSchedule({id:'day',schedule:[]});
dashboard.addSlot('2','08:00','09:00');
assert.equal(dashboard.draftSchedule().length,0,'Rest days reject assignments');
assert.match(dashboard.scheduleError(),/descanso/);
dashboard.routines.set([{id:'routine',name:'Fuerza',days:[{id:'day',name:'Piernas',schedule:[{weekday:3,start:'18:00',end:'19:00'},{weekday:3,start:'08:00',end:'09:00'}]}]}]);
assert.equal(dashboard.hasTraining(3),true);
assert.equal(dashboard.scheduledFor(3)[0].start,'08:00');
dashboard.selectCalendarDay(3);
assert.equal(dashboard.selectedCalendarDay(),3,'Click training day opens ribbon');
dashboard.selectCalendarDay(3);
assert.equal(dashboard.selectedCalendarDay(),null,'Second click closes ribbon');
dashboard.toggleRestDay(3);
assert.equal(dashboard.selectedCalendarDay(),3,'Training day cannot be marked as rest');
dashboard.clearAssignment('routine','day');
assert.equal(dashboard.routines().length,1,'Unassign must preserve the routine');
assert.equal(dashboard.routines()[0].days.length,1,'Unassign must preserve its day block');
assert.equal(dashboard.routines()[0].days[0].schedule.length,0);
assert.equal(saved.at(-1).length,0,'Unassign must persist the empty schedule');
assert.equal(dashboard.hasTraining(3),false,'Calendar must immediately free the day');
assert.equal(dashboard.selectedCalendarDay(),null);
dashboard.routines.set([{id:'routine',name:'Fuerza',days:[{id:'day',name:'Piernas',exercises:[{id:'exercise'}],schedule:[{weekday:3,start:'18:00',end:'19:00'},{weekday:1,start:'08:00',end:'09:00'}]}]}]);
assert.equal(dashboard.plannedEntries().length,2,'Same routine appears in the plan for each assigned slot');
assert.equal(dashboard.plannedEntries()[0].weekday,1,'Plan is ordered from Monday');
dashboard.removePlanEntry('routine','day',1,'08:00','09:00');
assert.equal(dashboard.plannedEntries().length,1,'Removing one plan entry preserves the other days');
assert.equal(dashboard.routines().length,1,'Library always keeps the routine');
assert.equal(dashboard.routines()[0].days[0].exercises.length,1,'Exercises are preserved');
dashboard.removePlanEntry('routine','day',3,'18:00','19:00');
assert.equal(dashboard.plannedEntries().length,0);
assert.equal(dashboard.routines().length,1,'Removing last assignment only removes it from Plan');
dashboard.toggleFavorite('routine',dashboard.routines()[0].days[0]);
assert.equal(dashboard.routines()[0].days[0].favorite,true);
dashboard.toggleFavorite('routine',dashboard.routines()[0].days[0]);
assert.equal(dashboard.routines()[0].days[0].favorite,false);
assert.equal(dashboard.isNewRoutine({createdAt:new Date().toISOString()}),true);
assert.equal(dashboard.isNewRoutine({createdAt:new Date(Date.now()-8*86400000).toISOString()}),false);
console.log('OK: guardado directo, sin duplicados, edición, eliminación e intervalos inválidos.');
